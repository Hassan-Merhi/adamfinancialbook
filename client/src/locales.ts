export const UI_CATALOG: Record<BookLanguage, Catalog> = { en: EN, fr: FR, ar: AR };

export function translateStatic(language: BookLanguage, source: string): string | null {
  if (language === 'en') return source;
  const exact = UI_CATALOG[language][source];
  if (exact !== undefined) return exact;

  const rules: Array<[RegExp, (match: RegExpMatchArray) => string]> = language === 'fr'
    ? [
        [/^(\d+) accounts?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'compte' : 'comptes'}`],
        [/^(\d+) businesses?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'entreprise' : 'entreprises'}`],
        [/^(\d+) projects?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'projet' : 'projets'}`],
        [/^(\d+) entries?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'écriture' : 'écritures'}`],
        [/^(\d+) latest$/, (m) => `${m[1]} plus récentes`],
        [/^(\d+) pinned$/, (m) => `${m[1]} épinglés`],
        [/^(\d+) total$/, (m) => `${m[1]} au total`],
        [/^(\d+) recorded$/, (m) => `${m[1]} enregistrés`],
        [/^(\d+) items? need attention$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'élément nécessite' : 'éléments nécessitent'} une action`],
        [/^(.+) between businesses$/, (m) => `${m[1]} entre entreprises`],
        [/^(.+) waiting for cash$/, (m) => `${m[1]} en attente d’encaissement`],
        [/^Today · (.+)$/, (m) => `Aujourd’hui · ${m[1]}`],
      ]
    : [
        [/^(\d+) accounts?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'حساب' : 'حسابات'}`],
        [/^(\d+) businesses?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'شركة' : 'شركات'}`],
        [/^(\d+) projects?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'مشروع' : 'مشاريع'}`],
        [/^(\d+) entries?$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'قيد' : 'قيود'}`],
        [/^(\d+) latest$/, (m) => `أحدث ${m[1]}`],
        [/^(\d+) pinned$/, (m) => `${m[1]} مثبتة`],
        [/^(\d+) total$/, (m) => `${m[1]} إجمالًا`],
        [/^(\d+) recorded$/, (m) => `${m[1]} مسجلة`],
        [/^(\d+) items? need attention$/, (m) => `${m[1]} ${Number(m[1]) === 1 ? 'عنصر يحتاج' : 'عناصر تحتاج'} متابعة`],
        [/^(.+) between businesses$/, (m) => `${m[1]} بين الشركات`],
        [/^(.+) waiting for cash$/, (m) => `${m[1]} بانتظار النقد`],
        [/^Today · (.+)$/, (m) => `اليوم · ${m[1]}`],
      ];

  for (const [pattern, render] of rules) {
    const match = source.match(pattern);
    if (match) return render(match);
  }
  return null;
}

